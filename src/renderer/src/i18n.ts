export type Key = keyof typeof en
export type T = (key: Key, vars?: Record<string, string | number>) => string

export function makeT(lang: Language): T {
  const dict = lang === 'th' ? th : en
  return (key, vars) => {
    let s = dict[key] ?? en[key] ?? key
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
    return s
  }
}

const ERRORS: Record<string, Key> = {
  DIRTY_ROOT: 'errDirtyRoot',
  NOT_A_REPO: 'errNotRepo',
  HAS_WORKSPACES: 'errHasWorkspaces',
  NAME_TAKEN: 'errNameTaken'
}

export function errorText(t: T, err: unknown): string {
  const msg = err instanceof Error ? err.message : String(err)
  return ERRORS[msg] ? t(ERRORS[msg]) : msg
}

export const TContext = createContext<T>(makeT('en'))
export const useT = (): T => useContext(TContext)
